    private void cargarMesas() {
        jComboBoxMesas.removeAllItems();
        mesasCargadas.clear();

        MesaDAO mesaDAO = new MesaDAO();

        try {
            List<Mesa> mesas = mesaDAO.obtenerTodos();
            mesasCargadas.addAll(mesas);
            for (Mesa mesa : mesas) {
                jComboBoxMesas.addItem(mesa.getNumeroMesa() + " - Capacidad: " + mesa.getCapacidad());
            }
        } catch (SQLException e) {
            String mensajeError = "Error al cargar mesas: " + e.getMessage();
            MensajeDialogFrame frameError = new MensajeDialogFrame(null, true, mensajeError, true);
            frameError.setVisible(true);
        }
    }

    private void recolectarDatosMesa() {
        this.errorEnRecolector = false;
        this.recolector = new RecolectorDeDatos();
        String mensajeError = "";

        try {
            this.capacidadMesa = recolector.recolectarEntero(jTextFieldCapacidad);

            if (capacidadMesa <= 0) {
                mensajeError = "La capacidad de la mesa debe ser mayor que cero.";
                mostrarMensajeErrorRecolector(mensajeError);
                return;
            }
        } catch (TextoVacioException e) {
            mensajeError = "El campo capacidad no puede estar vacio.";
            mostrarMensajeErrorRecolector(mensajeError);
            return;
        } catch (NumeroInvalidoException e) {
            mensajeError = "El campo capacidad contiene un número inválido.";
            mostrarMensajeErrorRecolector(mensajeError);
            return;
        }
    }

    private void cargarDatosMesaSeleccionada() {
        jTextFieldCapacidad.setText(String.valueOf(mesaSeleccionada.getCapacidad()));
    }

    private void limpiarCampos() {
        jTextFieldCapacidad.setText("");
    }

    private void mostrarMensajeErrorRecolector(String mensaje) {
        MensajeDialogFrame mensajeErrorFrame = new MensajeDialogFrame(null, true, mensaje, true);
        mensajeErrorFrame.setVisible(true);
        errorEnRecolector = true;
    }

