    private void mostrarMensajeError(String mensaje) {
        MensajeDialogFrame mensajeDialogFrame = new MensajeDialogFrame(null, true, mensaje, true);
        mensajeDialogFrame.setVisible(true);
    }

    private void abrirInternalResumen() {
        this.desktopPane.removeAll();
        InternalResumenPagos internalResumen = new InternalResumenPagos(pagosRealizados, balanceServicio);
        this.desktopPane.add(internalResumen);
        internalResumen.setVisible(true);
    }

