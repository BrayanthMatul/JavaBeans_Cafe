    private void jButtonPagoQuincenaActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButtonPagoQuincenaActionPerformed
        try {
            this.pagosRealizados = balanceServicio.realizarBalance(TipoPago.QUINCENA, false);
            abrirInternalResumen();
        } catch (SQLException ex) {
            String mensajeError = "Ocurrió un error al realizar el pago de la quincena. Por favor, inténtelo de nuevo más tarde.";
            mostrarMensajeError(mensajeError);
        } catch (NoEsFechaDePagoException ex) {
            String mensajeError = "No es fecha de pago de quincena. Por favor, inténtelo en la fecha correspondiente.";
            mostrarMensajeError(mensajeError);
        }
    }// GEN-LAST:event_jButtonPagoQuincenaActionPerformed

