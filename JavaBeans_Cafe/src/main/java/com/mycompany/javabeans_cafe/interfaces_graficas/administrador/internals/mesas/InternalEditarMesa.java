    private void jButtonSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButtonSeleccionarActionPerformed
        int indiceSeleccionado = jComboBoxMesas.getSelectedIndex();

        if (indiceSeleccionado == -1) {
            return;
        }

        this.mesaSeleccionada = mesasCargadas.get(indiceSeleccionado);

        cargarDatosMesaSeleccionada();
    }// GEN-LAST:event_jButtonSeleccionarActionPerformed

    private void jButtonRealizarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButtonRealizarActionPerformed
        if (mesaSeleccionada == null) {
            String mensajeError = "Debe seleccionar una mesa antes de editarla.";
            mostrarMensajeErrorRecolector(mensajeError);
            return;
        }

        recolectarDatosMesa();

        if (errorEnRecolector) {
            return;
        }

        MesaDAO mesaDAO = new MesaDAO();

        try {
            mesaDAO.actualizarCapacidad(mesaSeleccionada.getNumeroMesa(), capacidadMesa);
            mesaSeleccionada = null;
            String mensajeExito = "Mesa actualizada exitosamente.";
            MensajeDialogFrame frameExito = new MensajeDialogFrame(null, true, mensajeExito, false);
            frameExito.setVisible(true);
            limpiarCampos();
            cargarMesas();
        } catch (SQLException e) {
            String mensajeError = "Error al actualizar la mesa: " + e.getMessage();
            mostrarMensajeErrorRecolector(mensajeError);
        }
    }// GEN-LAST:event_jButtonRealizarActionPerformed

